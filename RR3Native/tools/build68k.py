# Discover code in ROM and emit recompiled C# (Gen68k.cs)
import os, sys, time
import analyze
from gen68k import Gen, gen_block, is_soft_end

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    rom = open(os.path.join(ROOT, 'rr3.bin'), 'rb').read()
    seeds = analyze.vectors(rom)[1:]
    extra = []
    sp = os.path.join(ROOT, 'seeds.txt')
    if os.path.exists(sp):
        for ln in open(sp):
            ln = ln.strip()
            if ln: extra.append(int(ln, 16))
    an = analyze.Analysis(rom)
    t0 = time.time()
    analyze.full_discovery(an, seeds, ptr_scan=True, extra=extra)
    entries = set(an.entries)
    # blocks also start after soft block ends
    for a, i in an.ins.items():
        if is_soft_end(i): entries.add(a + i.len)
    entries = sorted(e for e in entries if e in an.ins or analyze.Analysis.in_rom(an, e))
    print('discovery %.1fs: %d ins, %d blocks' % (time.time() - t0, len(an.ins), len(entries)))
    g = Gen(rom, len(rom))
    out = []
    out.append('// AUTO-GENERATED by tools/build68k.py from Road Rash 3 ROM. Do not edit.')
    out.append('using System;')
    out.append('namespace RR3 {')
    out.append('static partial class M68K {')
    names = []
    for e in entries:
        lines, seq = gen_block(g, e, an.ins, set(entries))
        nm = 'F_%06X' % e
        names.append((e, nm))
        out.append('    static uint %s() { unchecked {' % nm)
        out.extend(lines)
        out.append('    } }')
    out.append('    static void RegisterBlocks(Func<uint>[] t) {')
    for e, nm in names:
        out.append('        t[0x%X] = %s;' % (e >> 1, nm))
    out.append('    }')
    out.append('}')
    out.append('}')
    p = os.path.join(ROOT, 'runtime', 'Gen68k.cs')
    with open(p, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', p, len(out), 'lines')


if __name__ == '__main__':
    main()
