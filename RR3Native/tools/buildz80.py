# Extract the Z80 sound driver from the ROM and statically recompile it into C# (GenZ80.cs)
import os, sys
from z80gen import Z80Gen, ends_block

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DRIVER_ROM = 0x3B568
DRIVER_LEN = 0x1B27
# self-modifying instructions: 'jr $0583' at 0581 has its displacement byte rewritten (computed jump table)
SELFMOD = {0x0581: '((0x583 + (sbyte)Rd(0x582)) & 0xFFFF)',
           # 'jp $0000' at 1623 gets its target rewritten by 'ld ($1624),hl' (hl=$1629) at 106b
           0x1623: 'Rd16(0x1624)'}
EXTRA_SEEDS = [0x1629]
# instructions whose operand bytes are rewritten at run time: replacement C# code
OPERAND_PATCH = {
    # 'ld a,($0400)': low address byte stored by 'ld ($1637),a' at 1633 (DAC sample lookup table)
    0x1636: ['A = Rd(Rd16(0x1637));'],
}


def main(verbose=False):
    rom = open(os.path.join(ROOT, 'rr3.bin'), 'rb').read()
    img = bytearray(0x10000)
    img[0:DRIVER_LEN] = rom[DRIVER_ROM:DRIVER_ROM + DRIVER_LEN]
    g = Z80Gen(img)
    seeds = [0x0000] + list(range(0x583, 0x5A3, 4)) + EXTRA_SEEDS
    sp = os.path.join(ROOT, 'seeds_z80.txt')
    if os.path.exists(sp):
        seeds += [int(l, 16) for l in open(sp) if l.strip()]
    ins = {}
    entries = set(seeds)
    work = list(seeds)
    indirect = []
    while work:
        a = work.pop()
        while a not in ins and a < 0x2000:
            z = g.decode(a)
            if a in OPERAND_PATCH:
                z.code = list(OPERAND_PATCH[a]); z.text += '   ; operand patched at run time'
            if a in SELFMOD:
                z.flow = 'jpind'; z.cond = SELFMOD[a]; z.text += '   ; self-modified displacement'
            ins[a] = z
            nxt = (a + z.len) & 0xFFFF
            if z.target is not None and z.target < 0x2000:
                if z.target not in entries:
                    entries.add(z.target); work.append(z.target)
            if z.flow == 'jpind': indirect.append(z)
            if z.flow in ('cond', 'call', 'callcond', 'retcond', 'ei', 'halt'):
                if nxt not in entries:
                    entries.add(nxt); work.append(nxt)
                break
            if z.flow in ('jp', 'ret', 'jpind'):
                break
            a = nxt
    # safety net: any direct store into decoded code must be handled in SELFMOD
    import re
    owner = {}
    for a, z in ins.items():
        for k in range(z.len): owner[a + k] = a
    for a, z in sorted(ins.items()):
        m = re.match(r'ld \(\$([0-9a-f]{4})\),(\w+)', z.text)
        if not m: continue
        t = int(m.group(1), 16)
        w = 2 if m.group(2) not in ('a',) else 1
        hit = [owner[t + k] for k in range(w) if t + k in owner]
        if hit and not any(h in SELFMOD or h in OPERAND_PATCH for h in hit):
            print('WARNING: unhandled self-modifying store at %04x (%s) into code at %04x' % (a, z.text, hit[0]))
    print('z80: %d instructions, %d blocks, %d indirect' % (len(ins), len(entries), len(indirect)))
    if verbose:
        for a in sorted(ins):
            print('%04x  %s%s' % (a, '* ' if a in entries else '  ', ins[a].text))
    code_bytes = set()
    for a, z in ins.items():
        for k in range(z.len): code_bytes.add(a + k)
    out = ['// AUTO-GENERATED by tools/buildz80.py from the Road Rash 3 Z80 sound driver. Do not edit.',
           'using System;', 'namespace RR3 {', 'static partial class Z80 {']
    names = []
    for e in sorted(entries):
        if e not in ins: continue
        nm = 'Z_%04X' % e
        names.append((e, nm))
        out.append('    static int %s() {' % nm)
        a = e
        body = []
        cyc = 0
        ret = None
        while True:
            z = ins.get(a)
            if z is None:
                ret = 'Missing(0x%X)' % a; break
            body.append('        // %04x %s' % (a, z.text))
            body.extend('        ' + c for c in z.code)
            cyc += z.cyc
            nxt = (a + z.len) & 0xFFFF
            f = z.flow
            if f == 'next':
                a = nxt
                if a in entries:
                    ret = '0x%X' % a; break
                continue
            if f == 'jp': ret = '0x%X' % z.target
            elif f == 'cond':
                body.append('        if (%s) { Cyc += %d; return 0x%X; }' % (z.cond, z.cyc_taken, z.target)); ret = '0x%X' % nxt
            elif f == 'call':
                body.append('        Push(0x%X);' % nxt); ret = '0x%X' % z.target
            elif f == 'callcond':
                body.append('        if (%s) { Cyc += %d; Push(0x%X); return 0x%X; }' % (z.cond, z.cyc_taken, nxt, z.target)); ret = '0x%X' % nxt
            elif f == 'ret': ret = 'Pop()'
            elif f == 'retcond':
                body.append('        if (%s) { Cyc += %d; return Pop(); }' % (z.cond, z.cyc_taken)); ret = '0x%X' % nxt
            elif f == 'jpind': ret = z.cond
            elif f == 'halt':
                body.append('        Halted = true;'); ret = '0x%X' % nxt
            elif f == 'ei': ret = '0x%X' % nxt
            break
        out.append('        Cyc += %d;' % cyc)
        out.extend(body)
        out.append('        return %s;' % ret)
        out.append('    }')
    out.append('    static void RegisterBlocks(Func<int>[] t) {')
    for e, nm in names: out.append('        t[0x%X] = %s;' % (e, nm))
    out.append('    }')
    out.append('    public static readonly byte[] DriverImage = {%s};' % ','.join(str(x) for x in img[:DRIVER_LEN]))
    out.append('    public const int DriverRom = 0x%X;' % DRIVER_ROM)
    cb = sorted(code_bytes)
    out.append('    static readonly ushort[] PatchBytes = {0x582, 0x1624, 0x1625, 0x1637, 0x1638};')
    out.append('    static readonly ushort[] CodeBytes = {%s};' % ','.join(str(x) for x in cb))
    out.append('}', ) if False else None
    out.append('}')
    out.append('}')
    p = os.path.join(ROOT, 'runtime', 'GenZ80.cs')
    with open(p, 'w', newline='\n') as f: f.write('\n'.join(out))
    print('wrote', p)


if __name__ == '__main__':
    main('-v' in sys.argv)
